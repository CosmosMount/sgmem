"""Command-line entry points for baseline experiments and human failure analysis."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from sgmem.analysis import build_annotation_template, summarize_annotations
from sgmem.runner import CATEGORIES, DOMAINS, make_split, run


def _jsonl(paths: list[str]) -> list[dict]:
    rows = []
    for path in paths:
        with Path(path).open(encoding="utf-8") as handle:
            rows.extend(json.loads(line) for line in handle if line.strip())
    return rows


def _write_json(path: str, data: object, jsonl: bool = False) -> None:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("x", encoding="utf-8") as handle:
        if jsonl:
            for row in data:
                handle.write(json.dumps(row, ensure_ascii=False) + "\n")
        else:
            json.dump(data, handle, ensure_ascii=False, indent=2)
            handle.write("\n")


def main() -> None:
    parser = argparse.ArgumentParser(prog="sgmem", description="GroupMemBench local baselines and failure analysis")
    sub = parser.add_subparsers(dest="command", required=True)
    split = sub.add_parser("split", help="Create a question-level stratified development/test split")
    split.add_argument("--benchmark", default="external/GroupMemBench")
    split.add_argument("--domains", nargs="+", choices=DOMAINS, default=["Finance", "Technology"])
    split.add_argument("--seed", type=int, default=42)
    split.add_argument("--dev-fraction", type=float, default=0.25)
    split.add_argument("--output", required=True)

    experiment = sub.add_parser("run", help="Run one baseline against a local chat-completions endpoint")
    experiment.add_argument("--benchmark", default="external/GroupMemBench")
    experiment.add_argument("--project-root", default=".", help="Project checkout for Git provenance")
    experiment.add_argument("--domains", nargs="+", choices=DOMAINS, default=["Finance", "Technology"])
    experiment.add_argument("--categories", nargs="+", choices=CATEGORIES, default=list(CATEGORIES))
    experiment.add_argument("--method", choices=["bm25", "dense"], required=True)
    experiment.add_argument("--base-url", default="http://127.0.0.1:8000/v1")
    experiment.add_argument("--answer-model", required=True)
    experiment.add_argument("--judge-model", help="Defaults to the answer model")
    experiment.add_argument("--embedding-model", default="intfloat/e5-base-v2")
    experiment.add_argument("--embedding-revision")
    experiment.add_argument("--device", default=None, help="Sentence Transformers device, e.g. cpu or cuda")
    experiment.add_argument("--batch-size", type=int, default=32)
    experiment.add_argument("--top-k", type=int, default=10)
    experiment.add_argument("--timeout", type=float, default=120)
    experiment.add_argument("--limit", type=int, help="Maximum questions per selected domain/category")
    experiment.add_argument("--split", help="JSON file generated by the split command")
    experiment.add_argument("--partition", choices=["dev", "test", "all"])
    experiment.add_argument("--resume", action="store_true", help="Resume matching code/config/input; retry failed calls")
    experiment.add_argument("--output", required=True, help="New output directory; existing paths are not overwritten")

    template = sub.add_parser("annotate", help="Create a JSONL template for manually examining judged errors")
    template.add_argument("--records", nargs="+", required=True, help="One or more predictions.jsonl files")
    template.add_argument("--output", required=True)
    analysis = sub.add_parser("analyze", help="Summarize completed human annotations")
    analysis.add_argument("--records", nargs="+", required=True)
    analysis.add_argument("--annotations", nargs="+", required=True)
    analysis.add_argument("--output", required=True)

    args = parser.parse_args()
    if args.command == "split":
        _write_json(args.output, make_split(Path(args.benchmark), args.domains, args.seed, args.dev_fraction))
        print(f"Wrote split: {args.output}")
    elif args.command == "run":
        if bool(args.split) != bool(args.partition):
            parser.error("--split and --partition must be provided together")
        output = run(args)
        print(f"Results: {output}")
        metrics = json.loads((output / "metrics.json").read_text(encoding="utf-8"))
        if metrics["overall"]["errors"]:
            raise SystemExit("Some model calls failed; accuracy is unavailable. See predictions.jsonl.")
    elif args.command == "annotate":
        rows = build_annotation_template(_jsonl(args.records))
        _write_json(args.output, rows, jsonl=True)
        print(f"Wrote {len(rows)} unlabelled failure examples: {args.output}")
    else:
        summary = summarize_annotations(_jsonl(args.records), _jsonl(args.annotations))
        _write_json(args.output, summary)
        print(json.dumps(summary, ensure_ascii=False, indent=2))
